let LANG = "en";
try {
  const saved = localStorage.getItem("netpwn.lang");
  if (saved === "en" || saved === "es") LANG = saved;
} catch (e) { /* private mode */ }

function t(key, vars) {
  const table = STR[LANG] || STR.en;
  let s = table[key] || STR.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v ?? ""));
    }
  }
  return s;
}

function applyI18n() {
  document.documentElement.lang = LANG === "es" ? "es" : "en";
  document.querySelectorAll("[data-i18n]").forEach((n) => {
    n.textContent = t(n.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((n) => {
    n.innerHTML = t(n.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((n) => {
    n.placeholder = t(n.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((n) => {
    n.title = t(n.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-label]").forEach((n) => {
    n.setAttribute("aria-label", t(n.dataset.i18nLabel));
  });
  const sel = document.getElementById("lang");
  if (sel) sel.value = LANG;
  window.dispatchEvent(new CustomEvent("netpwn-lang"));
}

function setLang(lang) {
  LANG = lang === "es" ? "es" : "en";
  try { localStorage.setItem("netpwn.lang", LANG); } catch (e) { /* ignore */ }
  applyI18n();
}
